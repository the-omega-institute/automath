#!/usr/bin/env python3
"""Check finite instances of the paper's Fibonacci rank claims.

The computation uses only the Python standard library.  Fibonacci numbers
are generated by fast doubling, all F_d for d <= the requested bound are
factored completely by trial division, and ranks of apparition are then
recomputed directly modulo each prime factor.
"""

from __future__ import annotations

import argparse
import math
import platform
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Optional, Sequence, Tuple


PAPER_PRODUCT_CONSTANT = 2.0 / 3.0
GOLDEN_RATIO = (1.0 + math.sqrt(5.0)) / 2.0
LOG_GOLDEN_RATIO = math.log(GOLDEN_RATIO)


@dataclass(frozen=True)
class ExactRankRecord:
    rank: int
    fibonacci: int
    factorization: Tuple[Tuple[int, int], ...]
    primes: Tuple[int, ...]


@dataclass(frozen=True)
class FibotomicRecord:
    rank: int
    fibotomic_value: int
    exact_rank_radical: int
    product_margin: float
    entropy_margin: float
    binet_error: float
    binet_error_margin: float
    primitive_part: int
    primitive_ratio: int


@dataclass(frozen=True)
class LiftingRecord:
    prime: int
    rank: int
    u: int
    expected: int
    actual: int


@dataclass(frozen=True)
class ExceptionalPrimeRecord:
    two_first_failure_u: int
    two_expected: int
    two_actual: int
    five_formula_holds_on_test_range: bool
    five_rank_congruence_vacuous: bool


@lru_cache(maxsize=None)
def fibonacci(n: int) -> int:
    """Return F_n by exact fast doubling."""
    if n < 0:
        raise ValueError("n must be nonnegative")

    def pair(k: int) -> Tuple[int, int]:
        if k == 0:
            return 0, 1
        a, b = pair(k // 2)
        c = a * (2 * b - a)
        d = a * a + b * b
        return (d, c + d) if k % 2 else (c, d)

    return pair(n)[0]


def sieve_primes(limit: int) -> Tuple[int, ...]:
    """Return every prime at most limit by an Eratosthenes sieve."""
    if limit < 2:
        return tuple()
    composite = bytearray(limit + 1)
    for prime in range(2, math.isqrt(limit) + 1):
        if composite[prime]:
            continue
        start = prime * prime
        composite[start : limit + 1 : prime] = b"\x01" * (
            (limit - start) // prime + 1
        )
    return tuple(number for number in range(2, limit + 1) if not composite[number])


def factor_integer(value: int, primes: Sequence[int]) -> Tuple[Tuple[int, int], ...]:
    """Factor a positive integer using a prime table covering its square root."""
    if value < 1:
        raise ValueError("value must be positive")
    remaining = value
    factors = []
    for prime in primes:
        if prime * prime > remaining:
            break
        if remaining % prime:
            continue
        exponent = 0
        while remaining % prime == 0:
            remaining //= prime
            exponent += 1
        factors.append((prime, exponent))
    if remaining > 1:
        factors.append((remaining, 1))
    if math.prod(prime**exponent for prime, exponent in factors) != value:
        raise AssertionError(f"incomplete factorization of {value}")
    return tuple(factors)


def valuation(value: int, prime: int) -> int:
    """Return the prime-adic valuation of a positive integer."""
    if value < 1:
        raise ValueError("value must be positive")
    exponent = 0
    while value % prime == 0:
        value //= prime
        exponent += 1
    return exponent


@lru_cache(maxsize=None)
def rank_of_apparition(prime: int) -> int:
    """Compute the least positive d with p dividing F_d by modular iteration."""
    if prime < 2:
        raise ValueError("prime must be at least 2")
    previous, current = 0, 1
    for rank in range(1, 2 * prime + 3):
        previous, current = current, (previous + current) % prime
        if previous == 0:
            return rank
    raise AssertionError(f"no Fibonacci rank found for p={prime}")


def exact_rank_records(max_rank: int) -> Tuple[ExactRankRecord, ...]:
    """Factor F_3,...,F_max_rank and compute every exact-rank prime."""
    if max_rank < 3:
        raise ValueError("max_rank must be at least 3")
    prime_table = sieve_primes(math.isqrt(fibonacci(max_rank)))
    factorizations = {
        rank: factor_integer(fibonacci(rank), prime_table)
        for rank in range(3, max_rank + 1)
    }
    all_factors = sorted(
        {prime for factors in factorizations.values() for prime, _ in factors}
    )
    ranks = {prime: rank_of_apparition(prime) for prime in all_factors}
    records = []
    for rank in range(3, max_rank + 1):
        exact_primes = tuple(
            prime for prime in all_factors if ranks[prime] == rank
        )
        records.append(
            ExactRankRecord(
                rank=rank,
                fibonacci=fibonacci(rank),
                factorization=factorizations[rank],
                primes=exact_primes,
            )
        )
    return tuple(records)


def divisors(n: int) -> Tuple[int, ...]:
    return tuple(divisor for divisor in range(1, n + 1) if n % divisor == 0)


def mobius(n: int) -> int:
    if n == 1:
        return 1
    prime_count = 0
    remainder = n
    candidate = 2
    while candidate * candidate <= remainder:
        if remainder % candidate:
            candidate += 1
            continue
        remainder //= candidate
        if remainder % candidate == 0:
            return 0
        prime_count += 1
        while remainder % candidate == 0:
            remainder //= candidate
        candidate += 1
    if remainder > 1:
        prime_count += 1
    return -1 if prime_count % 2 else 1


def totient(n: int) -> int:
    result = n
    remainder = n
    prime = 2
    while prime * prime <= remainder:
        if remainder % prime:
            prime += 1
            continue
        result -= result // prime
        while remainder % prime == 0:
            remainder //= prime
        prime += 1
    if remainder > 1:
        result -= result // remainder
    return result


def fibotomic_integer(rank: int) -> int:
    """Evaluate the Mobius product defining the paper's fibotomic integer."""
    numerator = 1
    denominator = 1
    for divisor in divisors(rank):
        exponent = mobius(rank // divisor)
        if exponent == 1:
            numerator *= fibonacci(divisor)
        elif exponent == -1:
            denominator *= fibonacci(divisor)
    if numerator % denominator:
        raise AssertionError(f"nonintegral fibotomic product at rank {rank}")
    return numerator // denominator


def fibotomic_error_bound(terms: int = 100) -> float:
    """Compute C_F with a rigorous geometric upper bound for the omitted tail."""
    ratio = GOLDEN_RATIO**-2
    partial = math.fsum(
        abs(math.log1p(-((-ratio) ** index)))
        for index in range(1, terms + 1)
    )
    first_omitted = ratio ** (terms + 1)
    tail = first_omitted / ((1.0 - ratio) * (1.0 - first_omitted))
    return partial + tail


def entropy_value(rank: int, count: int, product_constant: float) -> float:
    half = count // 2
    return (
        count * math.log(product_constant * rank)
        + 2.0 * math.lgamma(half + 1)
        + (count - 2 * half) * math.log(half + 1)
    )


def _is_prime(value: int) -> bool:
    if value < 2:
        return False
    return all(value % divisor for divisor in range(2, math.isqrt(value) + 1))


def fibotomic_records(
    rank_records: Sequence[ExactRankRecord],
    product_constant: float = PAPER_PRODUCT_CONSTANT,
) -> Tuple[FibotomicRecord, ...]:
    """Check the exact-rank radical, entropy, Binet, and primitive-part claims."""
    if product_constant <= 0:
        raise ValueError("product_constant must be positive")
    error_bound = fibotomic_error_bound()
    results = []
    for rank_record in rank_records:
        rank = rank_record.rank
        fibotomic = fibotomic_integer(rank)
        radical = math.prod(rank_record.primes)
        entropy = entropy_value(rank, len(rank_record.primes), product_constant)
        product_margin = math.log(radical) - entropy
        if product_margin < -1e-12:
            raise AssertionError(
                f"fibotomic product bound failed at rank {rank}: "
                f"margin={product_margin:.12g}"
            )
        if fibotomic % radical:
            raise AssertionError(f"exact-rank radical failed at rank {rank}")
        binet_error = math.log(fibotomic) - totient(rank) * LOG_GOLDEN_RATIO
        binet_error_margin = error_bound - abs(binet_error)
        if binet_error_margin < -1e-12:
            raise AssertionError(
                f"Binet error bound failed at rank {rank}: "
                f"margin={binet_error_margin:.12g}"
            )
        entropy_margin = (
            totient(rank) * LOG_GOLDEN_RATIO + error_bound - entropy
        )
        if entropy_margin < -1e-12:
            raise AssertionError(
                f"entropy inequality failed at rank {rank}: "
                f"margin={entropy_margin:.12g}"
            )

        factor_exponents = dict(rank_record.factorization)
        primitive_part = math.prod(
            prime ** factor_exponents[prime] for prime in rank_record.primes
        )
        primitive_ratio = fibotomic // primitive_part
        if rank >= 13:
            if fibotomic % primitive_part:
                raise AssertionError(f"primitive part failed to divide at rank {rank}")
            if not (
                primitive_ratio == 1
                or (_is_prime(primitive_ratio) and rank % primitive_ratio == 0)
            ):
                raise AssertionError(
                    f"primitive-part ratio failed at rank {rank}: c_n={primitive_ratio}"
                )
            if not 1 <= primitive_ratio <= rank:
                raise AssertionError(
                    f"primitive-part ratio bound failed at rank {rank}: c_n={primitive_ratio}"
                )
        results.append(
            FibotomicRecord(
                rank=rank,
                fibotomic_value=fibotomic,
                exact_rank_radical=radical,
                product_margin=product_margin,
                entropy_margin=entropy_margin,
                binet_error=binet_error,
                binet_error_margin=binet_error_margin,
                primitive_part=primitive_part,
                primitive_ratio=primitive_ratio,
            )
        )
    return tuple(results)


def _lifting_values(prime: int, u_limit: int) -> Tuple[LiftingRecord, ...]:
    rank = rank_of_apparition(prime)
    base_exponent = valuation(fibonacci(rank), prime)
    return tuple(
        LiftingRecord(
            prime=prime,
            rank=rank,
            u=u,
            expected=base_exponent + valuation(u, prime),
            actual=valuation(fibonacci(rank * u), prime),
        )
        for u in range(1, u_limit + 1)
    )


def lifting_records(
    prime_limit: int, u_limit: int
) -> Tuple[Tuple[LiftingRecord, ...], ExceptionalPrimeRecord]:
    """Verify lifting for p outside {2,5} and expose both exclusions."""
    if prime_limit < 7:
        raise ValueError("prime_limit must be at least 7")
    if u_limit < 2:
        raise ValueError("u_limit must be at least 2")
    checked = []
    for prime in sieve_primes(prime_limit):
        if prime in (2, 5):
            continue
        for record in _lifting_values(prime, u_limit):
            if record.actual != record.expected:
                raise AssertionError(
                    f"lifting law failed at p={prime}, u={record.u}: "
                    f"expected={record.expected}, actual={record.actual}"
                )
            checked.append(record)

    two_records = _lifting_values(2, u_limit)
    two_failure = next(
        (record for record in two_records if record.actual != record.expected), None
    )
    if two_failure is None:
        raise AssertionError("p=2 did not expose the expected lifting exception")
    five_records = _lifting_values(5, u_limit)
    exceptions = ExceptionalPrimeRecord(
        two_first_failure_u=two_failure.u,
        two_expected=two_failure.expected,
        two_actual=two_failure.actual,
        five_formula_holds_on_test_range=all(
            record.actual == record.expected for record in five_records
        ),
        five_rank_congruence_vacuous=(rank_of_apparition(5) % 5 == 0),
    )
    return tuple(checked), exceptions


def _minimum(records: Sequence[FibotomicRecord], field: str) -> Tuple[float, int]:
    record = min(records, key=lambda item: getattr(item, field))
    return float(getattr(record, field)), record.rank


def run_verification(max_rank: int, prime_limit: int, u_limit: int) -> str:
    """Run the complete deterministic battery and return its text report."""
    ranks = exact_rank_records(max_rank)
    fibotomic = fibotomic_records(ranks)
    lifting, exceptions = lifting_records(prime_limit, u_limit)
    counts = " ".join(f"{record.rank}:{len(record.primes)}" for record in ranks)
    ratios = tuple(
        (
            len(record.primes) * math.log(record.rank) / totient(record.rank),
            record.rank,
        )
        for record in ranks
    )
    maximum_ratio, maximum_ratio_rank = max(ratios)
    product_margin, product_rank = _minimum(fibotomic, "product_margin")
    entropy_margin, entropy_rank = _minimum(fibotomic, "entropy_margin")
    binet_margin, binet_rank = _minimum(fibotomic, "binet_error_margin")
    largest_error_record = max(fibotomic, key=lambda record: abs(record.binet_error))
    primitive_records = tuple(record for record in fibotomic if record.rank >= 13)
    largest_primitive_ratio = max(
        primitive_records, key=lambda record: record.primitive_ratio
    )
    smallest_primitive_upper_margin = min(
        primitive_records, key=lambda record: record.rank - record.primitive_ratio
    )
    nontrivial_ratios = " ".join(
        f"{record.rank}:{record.primitive_ratio}"
        for record in primitive_records
        if record.primitive_ratio != 1
    ) or "none"
    error_bound = fibotomic_error_bound()
    perturbed_margin = math.log(3) - entropy_value(4, 1, 0.76)
    nonexceptional_prime_count = len(
        tuple(prime for prime in sieve_primes(prime_limit) if prime not in (2, 5))
    )
    lines = [
        "Fibonacci rank consistency verification",
        f"Python version: {platform.python_version()}",
        "Arithmetic: exact integers; floating-point logarithms only for reported margins",
        f"Exact ranks computed completely: 3 <= d <= {max_rank}",
        f"Exact-rank counts d:a(d): {counts}",
        "Classical exceptional counts: a(6)=0, a(12)=0",
        "Finite normalized exact-rank ratios a(d) log(d) / phi(d):",
        f"  maximum={maximum_ratio:.12f} at d={maximum_ratio_rank}",
        f"  asymptotic leading coefficient log(varphi)/2={LOG_GOLDEN_RATIO / 2.0:.12f}",
        "  (reported for scale only; the paper's o(1) has no finite threshold)",
        f"Fibotomic/radical checks: {len(fibotomic)} ranks",
        f"  Minimum fibotomic product margin log(radical)-H={product_margin:.12f} at d={product_rank}",
        f"  C_F upper bound used={error_bound:.12f}",
        f"  maximum observed |Binet error|={abs(largest_error_record.binet_error):.12f} at d={largest_error_record.rank}",
        f"  Minimum entropy margin phi(d)log(varphi)+C_F-H={entropy_margin:.12f} at d={entropy_rank}",
        f"  Minimum Binet-error margin C_F-|E_d|={binet_margin:.12f} at d={binet_rank}",
        f"Primitive-part ratios checked: 13 <= n <= {max_rank}",
        f"  nontrivial n:c_n values: {nontrivial_ratios}",
        f"  maximum c_n={largest_primitive_ratio.primitive_ratio} at n={largest_primitive_ratio.rank}",
        "  minimum upper-bound margin n-c_n="
        f"{smallest_primitive_upper_margin.rank - smallest_primitive_upper_margin.primitive_ratio} "
        f"at n={smallest_primitive_upper_margin.rank}",
        f"Lifting equalities checked: {len(lifting)} "
        f"({nonexceptional_prime_count} primes 3 <= p <= {prime_limit}, p not in {{2,5}}; 1 <= u <= {u_limit})",
        f"  p=2 first failure: u={exceptions.two_first_failure_u}, "
        f"expected={exceptions.two_expected}, actual={exceptions.two_actual}",
        f"  p=5: lifting formula held for 1 <= u <= {u_limit}, but z_5=5 is divisible by 5; "
        "the proposition's p-not-dividing-z consequence is inapplicable",
        "Sensitivity test: replacing 2/3 by 0.76 gives rank 4 product margin="
        f"{perturbed_margin:.12f}; the unit test requires rejection",
        "PASS: all stated finite checks and margins are nonnegative.",
    ]
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-rank", type=int, default=60)
    parser.add_argument("--prime-limit", type=int, default=200)
    parser.add_argument("--u-limit", type=int, default=24)
    parser.add_argument("--output", type=Path)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    report = run_verification(args.max_rank, args.prime_limit, args.u_limit)
    print(report, end="")
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
